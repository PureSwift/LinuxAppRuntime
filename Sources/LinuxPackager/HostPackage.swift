import Crypto
import Foundation

/// The SwiftPM package that builds an app's host (`Packager.md` §3): an
/// executable named after the app, linking `LinuxHostApp` and the app's
/// `libapp.a`. Generated in the work directory and reused between builds.
public struct HostPackage {

    /// The package's directory.
    public var directory: URL

    /// This repository's package, which the generated one depends on.
    public var hostPackage: URL

    public var executable: String

    /// The executable product. Not the app's name, which may be a product of
    /// a package in the graph already (AppRuntime's `ExampleUI` is); the
    /// packager names the copy it installs.
    public static let product = "LinuxAppMain"

    /// The app's `libapp.a`.
    public var library: URL

    public init(directory: URL, hostPackage: URL, executable: String, library: URL) {
        self.directory = directory
        self.hostPackage = hostPackage
        self.executable = executable
        self.library = library
    }

    /// Where this package's source is: `--host-package`, then
    /// `LINUXAPPRUNTIME_PATH`, then the tree `linux-app` was built from.
    public static func locate(_ explicit: String? = nil) throws(PackagerError) -> URL {
        let candidates = [explicit, ProcessInfo.processInfo.environment["LINUXAPPRUNTIME_PATH"]].compactMap { $0 }
            .map { URL(fileURLWithPath: $0) }
            + [URL(fileURLWithPath: #filePath).deletingLastPathComponent().deletingLastPathComponent().deletingLastPathComponent()]
        for candidate in candidates {
            let manifest = candidate.appendingPathComponent("Package.swift")
            if let text = try? String(contentsOf: manifest, encoding: .utf8), text.contains("name: \"LinuxAppRuntime\"") {
                return candidate.standardizedFileURL
            }
        }
        throw PackagerError("can't find LinuxAppRuntime's source; pass --host-package or set LINUXAPPRUNTIME_PATH")
    }

    /// Copies the app's library into the package as `lib/libapp-<hash>.a`.
    /// SwiftPM doesn't relink when a library in the linker flags changes,
    /// but a new name changes the manifest, which it does notice.
    public static func stage(_ library: URL, in directory: URL) throws(PackagerError) -> URL {
        guard let data = FileManager.default.contents(atPath: library.path) else {
            throw PackagerError("can't read \(library.path)")
        }
        let hash = SHA256.hash(data: data).prefix(8).map { String(format: "%02x", $0) }.joined()
        let lib = directory.appendingPathComponent("lib")
        let staged = lib.appendingPathComponent("libapp-\(hash).a")
        do {
            try FileManager.default.createDirectory(at: lib, withIntermediateDirectories: true)
            for old in try FileManager.default.contentsOfDirectory(atPath: lib.path) where old != staged.lastPathComponent {
                try FileManager.default.removeItem(at: lib.appendingPathComponent(old))
            }
            if !FileManager.default.fileExists(atPath: staged.path) {
                try data.write(to: staged)
            }
        } catch {
            throw PackagerError("can't copy \(library.path) into \(lib.path): \(error)")
        }
        return staged
    }

    var manifest: String {
        """
        // swift-tools-version:6.4
        // Generated by linux-app: the host for \(executable), linked with its library.
        import PackageDescription

        let package = Package(
            name: \(literal(executable + "Host")),
            products: [
                .executable(name: "\(Self.product)", targets: ["AppMain"]),
            ],
            dependencies: [
                .package(name: "LinuxAppRuntime", path: \(literal(hostPackage.path))),
            ],
            targets: [
                .executableTarget(
                    name: "AppMain",
                    dependencies: [.product(name: "LinuxHostApp", package: "LinuxAppRuntime")],
                    swiftSettings: [.swiftLanguageMode(.v5)],
                    linkerSettings: [.unsafeFlags([\(literal(library.path))])]
                ),
            ]
        )

        """
    }

    static let main = """
        // Generated by linux-app. The app's library defines these.
        import LinuxHostApp

        HostApp.main(AppEntryPoints(main: rt_main, dispatch: rt_dispatch, finalize: rt_finalize))

        """

    /// Writes the package, leaving files that haven't changed alone so
    /// builds stay incremental.
    public func write() throws(PackagerError) {
        let sources = directory.appendingPathComponent("Sources/AppMain")
        try write(manifest, to: directory.appendingPathComponent("Package.swift"))
        try write(Self.main, to: sources.appendingPathComponent("main.swift"))
        let version = hostPackage.appendingPathComponent(".swift-version")
        if let pinned = try? String(contentsOf: version, encoding: .utf8) {
            try write(pinned, to: directory.appendingPathComponent(".swift-version"))
        }
    }

    private func write(_ text: String, to url: URL) throws(PackagerError) {
        if (try? String(contentsOf: url, encoding: .utf8)) == text {
            return
        }
        do {
            try FileManager.default.createDirectory(at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
            try text.write(to: url, atomically: true, encoding: .utf8)
        } catch {
            throw PackagerError("can't write \(url.path): \(error)")
        }
    }

    /// Builds the host; the executable's path. `extraArguments` go to
    /// `swift build`, such as a Swift SDK for another architecture. With
    /// `staticSwift`, the Swift
    /// runtime, Foundation and Dispatch are linked in, so the app runs where
    /// Swift isn't installed.
    public func build(configuration: String, staticSwift: Bool = true, extraArguments: [String] = [],
                      runner: CommandRunning) throws(PackagerError) -> URL {
        try write()
        var arguments = ["swift", "build", "--package-path", directory.path, "--scratch-path",
                         directory.appendingPathComponent(".build").path, "-c", configuration, "--product", Self.product]
        if staticSwift {
            arguments.append("--static-swift-stdlib")
        }
        arguments += extraArguments
        // The host package links an app itself when this is set.
        let environment = ["LINUXAPPRUNTIME_APP_LIBRARY": ""]
        try runner.run(arguments, directory: directory, environment: environment)
        let bin = try runner.run(arguments + ["--show-bin-path"], directory: directory, environment: environment)
            .split(separator: "\n").last.map(String.init) ?? ""
        return URL(fileURLWithPath: bin.trimmingCharacters(in: .whitespaces)).appendingPathComponent(Self.product)
    }

    /// The AppRuntime checkout SwiftPM resolved for the build, if it cloned
    /// one.
    public var resolvedAppRuntime: URL? {
        let checkout = directory.appendingPathComponent(".build/checkouts/AppRuntime")
        return FileManager.default.fileExists(atPath: checkout.appendingPathComponent("Scripts/wasm2c-shim.py").path) ? checkout : nil
    }
}

/// A Swift string literal for `value`.
func literal(_ value: String) -> String {
    var escaped = ""
    for scalar in value.unicodeScalars {
        switch scalar {
        case "\\": escaped += "\\\\"
        case "\"": escaped += "\\\""
        case "\n": escaped += "\\n"
        case "\r": escaped += "\\r"
        case "\t": escaped += "\\t"
        default:
            if scalar.value < 0x20 {
                escaped += "\\u{\(String(scalar.value, radix: 16))}"
            } else {
                escaped.unicodeScalars.append(scalar)
            }
        }
    }
    return "\"\(escaped)\""
}

/// The wasm2c engine (`Packager.md` §2): AppRuntime's shim turns
/// `App.wasm` into a sealed `libapp.a`.
public struct Wasm2c {

    /// AppRuntime's checkout, for `Scripts/wasm2c-shim.py`.
    public var appRuntime: URL

    public init(appRuntime: URL) {
        self.appRuntime = appRuntime
    }

    /// AppRuntime from `--appruntime`, then `APPRUNTIME_PATH`.
    public static func locate(_ explicit: String?) -> URL? {
        [explicit, ProcessInfo.processInfo.environment["APPRUNTIME_PATH"]].compactMap { $0 }
            .map { URL(fileURLWithPath: $0) }
            .first { FileManager.default.fileExists(atPath: $0.appendingPathComponent("Scripts/wasm2c-shim.py").path) }
    }

    public func build(wasm: URL, output: URL, runner: CommandRunning) throws(PackagerError) -> URL {
        let script = appRuntime.appendingPathComponent("Scripts/wasm2c-shim.py").path
        try runner.run(["python3", script, "build", "--wasm", wasm.path, "--output", output.path], directory: nil, environment: [:])
        return output.appendingPathComponent("libapp.a")
    }
}
